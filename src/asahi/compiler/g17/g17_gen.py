"""
SPDX-License-Identifier: MIT

Generate the G17 (Apple M5) ISA tables for C from g17_isa.py (the single source of truth):
g17_isa.h (op/field enums, descriptor types) and g17_isa.c (descriptors, templates, opcode masks,
and the measured length model from g17_length.json).

usage: python3 g17_gen.py OUTDIR [--golden test/g17_golden_vectors.json]  (also emits g17_golden.h)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import g17_isa as ISA  # noqa: E402

KINDS = ["imm", "reg", "ureg", "enum", "flag", "hint", "pred"]
SIGNED_FIELDS = {("back_edge", "offset")}
MAX_LEN = 18


def c_ident(s):
    return "".join(ch if ch.isalnum() else "_" for ch in s).upper()


def kind_of(f):
    k = f.kind.strip()
    return k if k in KINDS else "imm"


ENUM_NAMES = {"s": "shift", "op": "bitop", "scale": "scale", "mask": "wrmask", "type": "cmptype"}   # enum field name -> C enum name (G17_<NAME>_<VALUE>)


def enum_constants():
    """C enums for the logical values of enum fields (from the field's mapping): G17_SHIFT_0 = raw, ..."""
    out = []
    seen = set()
    for insn in ISA.INSNS:
        for f in insn.fields.values():
            if kind_of(f) != "enum" or f.name in seen:
                continue
            seen.add(f.name)
            cname = ENUM_NAMES[f.name]
            names = [(f"G17_{c_ident(cname)}_{c_ident(str(v))}", raw) for v, raw in f.mapping.items()]
            out.append((cname, names))
    return out


def length_tables():
    m = ISA._length_model()
    rows = []
    for r in m["rows"]:
        if "const" in r:
            assert r["const"] < 0x80
            rows.append(r["const"])
        else:
            rows.append(0x80 | r["sub"])
    subs = []
    for t in m["subtables"]:
        assert all(n % 2 == 0 and n // 2 < 16 for n in t)
        # nibble-packed: entry i -> (byte i/2) >> (4*(i&1)), value = length/2
        packed = [((t[2 * i] // 2) | (t[2 * i + 1] // 2) << 4) for i in range(512)]
        subs.append(packed)
    return rows, subs, m["rules"]


def gen_header():
    L = []
    w = L.append
    w("/* Generated by g17_gen.py from g17_isa.py -- do not edit. */")
    w("/* SPDX-License-Identifier: MIT */")
    w("#pragma once\n")
    w("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n")
    w(f"#define G17_MAX_LENGTH {MAX_LEN}")
    w(f"#define G17_MAX_FIELDS {max(len(i.fields) for i in ISA.INSNS)}\n")
    w("enum g17_op {")
    for insn in ISA.INSNS:
        w(f"   G17_OP_{c_ident(insn.name)},")
    w("   G17_NUM_OPS,")
    w("   G17_OP_UNKNOWN = G17_NUM_OPS,")
    w("};\n")
    w("enum g17_field_kind {")
    for k in KINDS:
        w(f"   G17_FIELD_{c_ident(k)},")
    w("};\n")
    w("/* Field indices, per op (index into g17_op_info[op].fields and g17_instr.raw). */")
    for insn in ISA.INSNS:
        if not insn.fields:
            continue
        w(f"enum {{ " + ", ".join(f"G17_{c_ident(insn.name)}_{c_ident(n)} = {i}"
                                   for i, n in enumerate(insn.fields)) + " };")
    w("")
    w("/* Raw encodings of enum-valued fields. */")
    for cname, names in enum_constants():
        w(f"enum g17_{cname} {{ " + ", ".join(f"{n} = {r}" for n, r in names) + " };")
    w("")
    w("struct g17_bitpos {\n   uint8_t byte, bit;\n};\n")
    w("struct g17_field_info {")
    w("   const char *name;")
    w("   enum g17_field_kind kind;")
    w("   uint8_t width;")
    w("   bool is_signed;")
    w("   uint32_t default_raw;            /* written when the caller leaves the field unset */")
    w("   const struct g17_bitpos *pos;    /* LSB first */")
    w("};\n")
    w("struct g17_op_info {")
    w("   const char *name;")
    w("   const char *family;")
    w("   uint8_t length;")
    w("   uint8_t num_fields;")
    w("   uint16_t specificity;            /* popcount of the opcode mask (decode tie-break) */")
    w("   const uint8_t *tmpl;")
    w("   const uint8_t *mask;             /* bits not owned by any field */")
    w("   const uint8_t *match;            /* tmpl & mask */")
    w("   const struct g17_field_info *fields;")
    w("};\n")
    w("extern const struct g17_op_info g17_op_info[G17_NUM_OPS];\n")
    w("/* Length model: ordered byte-pattern rules, then a two-level table keyed on")
    w(" * row = b0&7 | b1.7 (move family) | b2&7 and col = b4&7 | b6&0xf | b8&7. */")
    w("struct g17_length_rule {\n   uint8_t mask[14], match[14], length;\n};\n")
    w("extern const struct g17_length_rule g17_length_rules[];")
    w("extern const unsigned g17_num_length_rules;")
    w("extern const uint8_t g17_length_rows[128];        /* < 0x80: length in bytes; else 0x80|sub-table */")
    w("extern const uint8_t g17_length_sub[][512];       /* nibble-packed length/2, 1024 entries each */")
    return "\n".join(L) + "\n"


def c_bytes(b):
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_source():
    L = []
    w = L.append
    w("/* Generated by g17_gen.py from g17_isa.py -- do not edit. */")
    w("/* SPDX-License-Identifier: MIT */\n")
    w('#include "g17_isa.h"\n')
    for insn in ISA.INSNS:
        n = c_ident(insn.name).lower()
        w(f"static const uint8_t tmpl_{n}[] = {c_bytes(insn.template)};")
        w(f"static const uint8_t mask_{n}[] = {c_bytes(insn.fixed_mask)};")
        w(f"static const uint8_t match_{n}[] = {c_bytes(insn.match)};")
        for fname, f in insn.fields.items():
            pos = ", ".join(f"{{{b}, {bit}}}" for b, bit in f.positions)
            w(f"static const struct g17_bitpos pos_{n}_{fname}[] = {{{pos}}};")
        if insn.fields:
            w(f"static const struct g17_field_info fields_{n}[] = {{")
            for fname, f in insn.fields.items():
                signed = "true" if (insn.name, fname) in SIGNED_FIELDS else "false"
                w(f"   {{{c_str(fname)}, G17_FIELD_{c_ident(kind_of(f))}, {f.width}, {signed}, "
                  f"{insn.defaults[fname]}u, pos_{n}_{fname}}},")
            w("};")
        w("")
    w("const struct g17_op_info g17_op_info[G17_NUM_OPS] = {")
    for insn in ISA.INSNS:
        n = c_ident(insn.name).lower()
        spec = sum(bin(b).count("1") for b in insn.fixed_mask)
        fields = f"fields_{n}" if insn.fields else "NULL"
        w(f"   [G17_OP_{c_ident(insn.name)}] = {{{c_str(insn.name)}, {c_str(insn.family)}, {insn.length}, "
          f"{len(insn.fields)}, {spec}, tmpl_{n}, mask_{n}, match_{n}, {fields}}},")
    w("};\n")
    rows, subs, rules = length_tables()
    w("const struct g17_length_rule g17_length_rules[] = {")
    for r in rules:
        w(f"   {{{c_bytes(r['mask'])}, {c_bytes(r['match'])}, {r['length']}}},")
    w("};")
    w(f"const unsigned g17_num_length_rules = {len(rules)};\n")
    w("const uint8_t g17_length_rows[128] = {")
    for i in range(0, 128, 16):
        w("   " + ", ".join(f"0x{x:02x}" for x in rows[i:i + 16]) + ",")
    w("};\n")
    w(f"const uint8_t g17_length_sub[{len(subs)}][512] = {{")
    for t in subs:
        w("   {")
        for i in range(0, 512, 32):
            w("      " + ", ".join(f"0x{x:02x}" for x in t[i:i + 32]) + ",")
        w("   },")
    w("};")
    return "\n".join(L) + "\n"


def gen_golden(path):
    """test/g17_golden_vectors.json (kernels that ran on an M5 with the expected output) -> C array."""
    import json
    V = json.load(open(path))["vectors"]
    L = ["/* Generated by g17_gen.py from g17_golden_vectors.json -- do not edit. */",
         "/* SPDX-License-Identifier: MIT */", "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "",
         "struct g17_golden {\n   const char *name;\n   const uint8_t *code;\n   size_t size;\n};", ""]
    progs = []                       # every program: the kernel body, plus its preamble when it has one
    for v in V:
        progs.append((v["name"], bytes.fromhex(v["code_hex"])))
        if v.get("preamble_hex"):
            progs.append((v["name"] + " [preamble]", bytes.fromhex(v["preamble_hex"])))
    for i, (name, code) in enumerate(progs):
        L.append(f"static const uint8_t g17_golden_code_{i}[] = {c_bytes(code)};")
    L.append("\nstatic const struct g17_golden g17_golden[] = {")
    for i, (name, code) in enumerate(progs):
        L.append(f"   {{{c_str(name)}, g17_golden_code_{i}, sizeof(g17_golden_code_{i})}},")
    L.append("};")
    return "\n".join(L) + "\n"


def main(outdir, golden=None):
    ISA.validate_tables()
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "g17_isa.h"), "w") as f:
        f.write(gen_header())
    with open(os.path.join(outdir, "g17_isa.c"), "w") as f:
        f.write(gen_source())
    if golden:
        with open(os.path.join(outdir, "g17_golden.h"), "w") as f:
            f.write(gen_golden(golden))


if __name__ == "__main__":
    args = sys.argv[1:]
    golden = None
    if "--golden" in args:
        i = args.index("--golden")
        golden = args[i + 1]
        del args[i:i + 2]
    main(args[0] if args else ".", golden)
